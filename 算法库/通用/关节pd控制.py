"""
关节pd控制.py —— 最简单的控制插件（把教程 11 号脚本的算法搬进外壳）

（文件名不能以数字开头，否则 Python 不能 import；加载顺序由主程序里的列表决定）

这是"一个控制插件"的标准长相：
    ├─ 类属性：名称/版本/说明（给启动清单显示）
    ├─ 收到模型()：可选。需要缓存 model/data 时才写（本插件不用，因为每步都能从 event 拿到）
    └─ 每步控制()：★ 必写。读状态 → 算力矩 → 写 event.data.ctrl[:]

算法本体只有 3 行（和教程 11 号脚本一模一样）：
    误差 = 目标 - 当前位置
    力矩 = KP*误差 - KD*速度          ← 弹簧 + 阻尼（PD）
    return 力矩 + 重力补偿项           ← 不加这句机械臂会砸下来

想看它动起来：把下面 启动时动作 改成 "抬臂"（或直接改 目标角），重启即可。
"""
from __future__ import annotations

import numpy as np

import 插件系统 as 插件                       # 我们自己的兼容层（唯一碰官方 API 的地方）
from 插件系统 import 控制插件, 每步

try:                                          # 界面桥是可选的：没有它也能单独跑本插件
    from 界面桥 import 面板目标消息
except Exception:                             # noqa: BLE001
    class 面板目标消息:                        # 占位类型（保证 @每步 的类型标注仍然合法）
        ctrl_target = None


class 关节PD控制插件(控制插件):
    名称 = "关节 PD 位置控制"
    版本 = "1.1"
    英文名 = "Joint PD position control"   # 面板上显示用（官方 UI 字体没有中文字形，面板只能画 ASCII）
    说明 = "6 个关节各自做 PD + 重力补偿。可在界面的 Controls 面板里拖滑杆实时改目标。"
    作者 = "数字样机"

    # ---- 调参入口（改这里就能调"性格"）----
    KP = 200.0            # 弹簧刚度：越大越硬、追得越快；太大 → 抖
    KD = 30.0             # 阻尼：越大越稳；太小 → 到位后来回晃
    启动时动作 = "抬臂"    # "保持不动"＝停在 home 姿势；"抬臂"＝抬 20° 演示一下
    听界面滑杆 = True      # True：界面 Controls 面板的滑杆说了算（拖了立刻跟过去）

    def __init__(self):
        self.目标 = None          # 第一次调用时才知道 home 姿势，所以先留空
        self.步数 = 0
        self.当前误差 = float("nan")
        self.最大误差 = 0.0
        self.界面目标 = None      # 来自界面滑杆（由 界面桥.py 每帧发过来）
        self.最后一次力矩 = np.zeros(6)

    # ------------------------------------------------------------------
    # 兼容性预检：外壳换模型时会先问一句"这个模型你能跑吗"
    #   （契约见 软件/插件系统.py 的 `控制插件.模型兼容性`）
    # ------------------------------------------------------------------
    def 模型兼容性(self, 模型) -> str:
        """要求"每个关节都有自己的力矩执行器"，也就是 nu == nq（扭矩模型）。

        为什么必须有这一条：本算法的核心就是
            `数据.ctrl[:] = KP*误差 - KD*qvel + qfrc_bias`
        —— "一个关节一个力矩"。如果执行器比关节少（位置伺服模型、带夹爪的模型），
        `ctrl[:]` 的长度就和 qpos 对不上：要么越界，要么只驱动前几个关节，
        表现出来是"机械臂乱动"或"报错后被停用"。
        以前只能靠"跑起来抛异常 → 出错隔离停用"发现，代价是**不可恢复**，
        而且界面上照样显示它挂着。现在装配时就挡掉，并把原因写给界面。
        """
        nq = int(getattr(模型, "nq", 0))
        nu = int(getattr(模型, "nu", 0))
        if nq == 0 or nu == 0:
            return "模型没有关节或执行器（空场景 / 纯展示模型）"
        if nu != nq:
            return f"需要 nu==nq 的扭矩模型（本模型 nq={nq}、nu={nu}）"
        return ""

    # ------------------------------------------------------------------
    # 可选：界面滑杆的值（界面桥.py 每帧发一条快照过来）
    # ------------------------------------------------------------------
    @每步
    def 收到面板目标(self, 消息: 面板目标消息) -> bool:
        try:
            self.界面目标 = 消息.ctrl_target.copy()
        except Exception:                                     # noqa: BLE001
            pass
        return False

    # ------------------------------------------------------------------
    # ★ 每转一圈仿真，这个方法被调用一次
    # ------------------------------------------------------------------
    @每步
    def 每步控制(self, event: 插件.messages.StepEvent) -> bool:
        模型, 数据 = event.model, event.data

        # ★ 空场景（模型/空场景.xml）里 nq = nv = nu = 0，没有关节可控制。
        #   不判断的话下面 目标[1] 会越界 —— 实测会抛 IndexError，插件被"出错隔离"
        #   停用，之后即使换了真模型也不会被控制，只能重启。所以先挡一道。
        if 数据.qpos.size < 3 or 数据.ctrl.size == 0:
            self.目标 = None            # 换成真模型后，重新以新模型的姿势为基准
            return False

        if self.目标 is None:                       # 第一次：用 home 姿势当基准
            self.目标 = 数据.qpos.copy()
            if self.启动时动作 == "抬臂":
                self.目标[1] += 0.35            # shoulder_lift 抬一点
                self.目标[2] -= 0.35            # elbow 收一点

        # 目标优先级：界面滑杆（拖过就听它的）> 本文件里写的目标
        目标 = self.目标
        if (self.听界面滑杆 and self.界面目标 is not None
                and len(self.界面目标) == len(数据.qpos)):
            目标 = self.界面目标

        误差 = 目标 - 数据.qpos
        数据.ctrl[:] = self.KP * 误差 - self.KD * 数据.qvel + 数据.qfrc_bias
        self.最后一次力矩 = 数据.ctrl.copy()

        self.步数 += 1
        self.当前误差 = float(np.abs(误差).max())
        self.最大误差 = max(self.最大误差, self.当前误差)
        return False            # 返回 False = 不拦截（让别的插件也能看到这一步）

    # ------------------------------------------------------------------
    # ★ 可调参数：界面上会出现滑杆，拖动**实时生效**（不用改文件、不用重启）
    #   键名必须是本插件的类属性名（KP / KD）。
    # ------------------------------------------------------------------
    def 可调参数(self) -> dict:
        return {
            "KP": {"值": self.KP, "范围": (10.0, 20000.0), "单位": "N/m"},
            "KD": {"值": self.KD, "范围": (0.0, 500.0), "单位": "N·s/m"},
        }

    # ------------------------------------------------------------------
    # ★ 可选：给监控面板看的指标（键=曲线名，值=数字）
    #   写在这里的数会自动出现在界面的 Monitor 窗口里 —— 不用改外壳、不用改面板。
    # ------------------------------------------------------------------
    def 指标(self) -> dict:
        if self.目标 is None:
            return {}
        return {
            "最大误差(deg)": float(np.degrees(self.当前误差)),
            "力矩峰值(Nm)" : float(np.abs(self.最后一次力矩).max()),
        }

    # ------------------------------------------------------------------
    def 插件状态(self) -> dict:
        if self.目标 is None:
            return {"状态": "等待第一步"}
        来源 = "界面滑杆" if (self.听界面滑杆 and self.界面目标 is not None) else "文件里的目标"
        return {"步数": self.步数,
                "当前误差": f"{np.degrees(self.当前误差):.3f}°",
                "历史最大": f"{np.degrees(self.最大误差):.3f}°",
                "目标来源": 来源}
