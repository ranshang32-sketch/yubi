    global 插件清单, 启动项目名

    #   顺序说明：`--项目` / `--无插件` 在命令行解析之前无法生效（模块导入时就已经
    #   装配过一次），所以这里按命令行重新装配一遍覆盖它 —— 装配只读文件，成本极低。
    if args.列项目:
        return 打印项目总览()
