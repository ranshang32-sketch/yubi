def 决定启动模型() -> tuple[str, str]:
    """返回 (模型路径, 选它的原因)。空串表示一个都找不到。"""
    try:
        import 模型桥
        上次 = 模型桥.读取上次模型()
        if 上次:
            return 上次, "上次用过的模型（想换成空场景：删 输出/设置.json，或加 --空场景）"
    except Exception:                                                 # noqa: BLE001
        pass
    if os.path.exists(空场景路径):
        return 空场景路径, "空场景（首次启动；在窗口里用【模型库】面板选一台机械臂）"
    for p in 模型候选路径:
        if os.path.exists(p):
            return p, "兜底：老结构的 UR5e（没找到空场景文件）"
    return "", ""


启动模型, 启动模型原因 = 决定启动模型()


def 决定启动项目(模型路径: str, 指定项目: str = "") -> str:
    """决定启动时装哪个项目。返回项目名（空串 = 不挂任何算法）。

    优先级（从高到低）：
        ① 命令行 `--项目 xxx`      （明确指定了就用它）
        ② 上次用的项目              （方案 C 的"接着上次干活"）
        ③ 启动模型所属的项目        （按项目文件里的 `模型` 字段反查）
        ④ 空                        （空场景 / 新导入的模型 → 不挂算法，与以前一致）
    """
    if 指定项目:
        return 指定项目 if 项目清单.读项目(指定项目) else ""
    上次 = 项目清单.读取上次项目()
    if 上次:
        return 上次
    return 项目清单.按模型找项目(模型路径) if 模型路径 else ""


