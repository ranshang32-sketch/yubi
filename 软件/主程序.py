    try:
        from 骨架 import 官方接口清单 as 接口
        正常数, 失败数 = 接口.全量检查(只列失败=not args.自检)
        if 失败数:
            print(f"  ⚠ 官方接口自检：{正常数} 项正常、**{失败数} 项失败**（上面已列出该改哪里）")
            print("     → 可能是官方升级了 mujoco。修好后重跑；或把 mujoco 降回实测版本：")
            print("       .venv/bin/pip install \"mujoco==3.13.0\"")
        else:
            print(f"  ✓ 官方接口自检：{正常数} 项全部正常（窗口/渲染/面板/消息机制都还在）")
    except Exception as 异常:                                      # noqa: BLE001
        print(f"  ⚠ 官方接口自检本身跑不起来：{type(异常).__name__}: {异常}")
