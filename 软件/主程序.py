def 打印项目总览() -> int:
    """`--列项目`：不开窗口，把"项目 ↔ 模型 ↔ 算法"三者的对应关系打出来。

    为什么值得有这条命令：方案 C 之后"算法从哪来"变成了数据（项目文件 + 算法库），
    数据最容易出的问题是**对不上**（项目里写了一个算法名，但算法库里没有那个文件；
    或者算法库里躺着几个从没被任何项目用到的算法）。这条命令就是那张对照表。
    """
    print("=" * 78)
    print("  项目总览（方案 C：项目 = 模型 + 算法列表 + 参数 的命名快照）")
    print("=" * 78)

    项目们 = 项目清单.列出项目()
    print(f"\n【项目】共 {len(项目们)} 个（目录：{项目清单.相对包根(项目清单.项目目录)}）")
    for 名 in 项目们:
        数据 = 项目清单.读项目(名) or {}
        模型 = str(数据.get("模型") or "")
        模型绝对 = 项目清单.绝对(模型)
        存在 = "✓" if os.path.exists(模型绝对) else "✗ 文件不在"
        算法条目 = 项目清单.解析算法(数据)
        参数 = 数据.get("参数") or {}
        参数数 = sum(len(v or {}) for v in 参数.values())
        print(f"\n  · {名}")
        print(f"      模型：{模型 or '（没写）'}   [{存在}]")
        print(f"      算法：{len(算法条目)} 个 —— "
              + ("、".join(str(a.get('插件')) for a in 算法条目) if 算法条目 else "（空）"))
        if 参数数:
            print(f"      参数：{参数数} 个已保存的值（" +
                  "、".join(f"{k}×{len(v or {})}" for k, v in 参数.items()) + "）")
        if 数据.get("备注"):
            print(f"      备注：{数据['备注']}")

    算法们 = 项目清单.发现的算法()
    print(f"\n【算法库】共 {len(算法们)} 个（目录：{项目清单.相对包根(项目清单.算法库目录)}）")
    for d in 算法们:
        分组 = d["分组"] or "（根）"
        print(f"  · [{分组}] {d['插件']:16} {d['相对包根']}")

    # 交叉检查：项目里引用的算法 vs 算法库里实际有的
    被引用 = set()
    for 名 in 项目们:
        for a in 项目清单.解析算法(项目清单.读项目(名)):
            被引用.add(str(a.get("插件")))
    全部 = {d["插件"] for d in 算法们}
    没被用的 = sorted(全部 - 被引用)
    缺失的 = sorted(被引用 - 全部)
    print("\n【交叉检查】")
    print(f"  · 没被任何项目用到的算法：{'、'.join(没被用的) if 没被用的 else '无'}")
    print(f"  · 项目里引用了但算法库没有的：{'、'.join(缺失的) if 缺失的 else '无'}")
    print(f"  · 方案 C 之前的老算法目录 软件/plugins/："
          f"{'还在（见 项目.发现的算法 的第二个扫描根）' if os.path.isdir(os.path.join(本目录, 'plugins')) else '已清空'}")
    print()
    return 1 if 缺失的 else 0


