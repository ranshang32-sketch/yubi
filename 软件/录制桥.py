"""
录制桥.py —— 「录制/回放」界面↔仿真侧的消息定义（第 4 步 D2 的"合同"）

为什么要把消息定义单独放一个文件（这是踩过两次的坑）
----------------------------------------------------------------------------
小软件的界面（窗口线程）和算法（仿真线程）只能靠消息通信，而消息能不能送达，
**取决于两边引用的那个消息类是不是同一个对象** —— 因为仿真侧的派发是：

    if not issubclass(type(消息), info.message_type):   # 类型不匹配就静默跳过
        continue

★ 第一次踩（2026-09-18，用户报"按 Start 完全没反应"）：
  `录制命令` 定义在 `数据录制.py` 里。外壳用 `from plugins.数据录制 import …` 加载插件，
  面板却用 `sys.path.insert(0, 软件/plugins)` + `from 数据录制 import …` ——
  **同一个 .py 被加载了两遍，成了两个模块对象**，两边的 `录制命令` 不是同一个类。
  结果是按 Start/Stop/Replay 毫无反应，且不报任何错。

★ 第二次踩（方案 C 迁移）：算法文件搬到 `算法库/通用/` 之后，装配器用
  **按文件路径生成的唯一模块名**（如 `驭臂算法.算法库.通用.数据录制`）来 import ——
  这是为了修"两个同名算法文件互相覆盖"的问题（见 装配器.py）。于是
  `from plugins.数据录制 import 录制命令` 这条路彻底断了（ModuleNotFoundError）。

两次的根因是同一个：**消息的定义跟着"谁实现的"走，而不是跟着"谁和谁通信"走**。
所以现在把它放到这里：这是界面与仿真侧**共同的邻居**，双方都从这里 import，
模块名永远是 `录制桥`，不随算法文件搬到哪里而变。

同样的安排在本项目里已经有三处（照这个模式做就对了）：
    `界面桥.py`  —— 控制面板滑杆值（界面 → 仿真）
    `指标桥.py`  —— 插件指标曲线（仿真 → 界面）
    `辨识桥.py`  —— 参数辨识命令与状态（双向）
本文件是第四个成员。

改这个文件时要注意：**动了字段就等于改了协议**，界面与仿真侧必须同时更新
（`数据录制插件` 在 `算法库/通用/数据录制.py`，界面在 `软件/面板/录制面板.py`）。
"""
from __future__ import annotations

import dataclasses

from mujoco.experimental.studio import messages


@dataclasses.dataclass(frozen=True)
class 录制命令(messages.Snapshot):
    """录制/回放命令（界面 → 仿真侧）。

    Snapshot 语义 = 只保留最新一条，不需要排队 —— 用户连点几下 Start/Stop 时，
    过期的那些本来也不该被逐个执行。
    """

    动作: str = "空闲"        # "开始" / "停止" / "回放" / "空闲"
    频率: float = 100.0       # 录制频率 Hz（默认会被对齐到物理步长，见 数据录制插件）
    备注: str = ""            # 写进元信息的说明（比如"KP=200 测试"）
