"""
验收面板文字.py —— 确保"面板上不会再出现问号"（不开窗，秒级）

为什么要有它：
    官方 UI 字体（Atkinson Hyperlegible）是纯拉丁字体，没有任何中文字形，
    ImGui 遇到缺字形会回退画 `?` —— 面板上就成了一串问号。
    治本办法是把"面板上要显示的每一个字"都过一遍 ASCII 检查。
    这个脚本就是那遍检查：**不靠肉眼，靠断言**。

它查 5 件事：
    ① 7 个自研面板的名字都能翻成 ASCII（About 面板会列出面板清单）
    ② 每个插件都有非空且 ASCII 的 `英文名`（面板上显示的就是它）
    ③ 已知的动态文本（模型状态/辨识状态/进度/指标名/空场景名/录制状态…）
       都能翻成 ASCII，而且**不会翻错**（回归检查：单字替换踩过的坑）
    ④ 曲线名（来自插件 指标()）会变成 ASCII 且互不重名（曲线基类负责唯一化）
    ⑤ 静态扫描（转调 字体覆盖.py）：面板代码里的字面量全部画得出来

跑法：
    .venv/bin/python 优化/验证/验收面板文字.py
"""
from __future__ import annotations

import os
import subprocess
import sys

本目录 = os.path.dirname(os.path.abspath(__file__))
包根 = os.path.dirname(os.path.dirname(本目录))
软件目录 = os.path.join(包根, "软件")
for p in (软件目录, os.path.join(软件目录, "面板"), os.path.join(软件目录, "plugins")):
    if p not in sys.path:
        sys.path.insert(0, p)

import 界面文字                                                        # noqa: E402

通过 = 失败 = 0


def 断言(名: str, 好: bool, 说明: str = "") -> None:
    global 通过, 失败
    if 好:
        通过 += 1
    else:
        失败 += 1
    print(f"  {'✓' if 好 else '✗'} {名}{('　' + 说明) if 说明 else ''}")


# ---------------------------------------------------------------------------
# ① 面板名
# ---------------------------------------------------------------------------
print("① 面板名能翻成 ASCII")
面板名 = ["模型库", "外观", "关于", "控制器参数", "数据录制", "实时监控", "参数辨识"]
for 名 in 面板名:
    英 = 界面文字.英文(名)
    断言(f"面板【{名}】", bool(英) and 界面文字.可用(英), f"→ {英!r}")
断言("面板名互不重复", len({界面文字.英文(n) for n in 面板名}) == len(面板名),
     f"（{len(面板名)} 个名字 → {len({界面文字.英文(n) for n in 面板名})} 个英文名）")

# ---------------------------------------------------------------------------
# ② 插件的 英文名
# ---------------------------------------------------------------------------
print("\n② 插件的 英文名")
插件文件 = sorted(f for f in os.listdir(os.path.join(软件目录, "plugins"))
              if f.endswith(".py") and not f.startswith("_"))
for 文件 in 插件文件:
    模块 = __import__(文件[:-3])
    # 只查**本模块里定义**的具体插件类：排除 import 进来的基类
    # （插件系统.控制插件 的名称是"未命名插件"，那是基类，不该要求它声明英文名）
    找到 = [v for v in vars(模块).values()
           if isinstance(v, type)
           and getattr(v, "__module__", "") == 模块.__name__
           and str(getattr(v, "名称", "")) not in ("", "未命名插件")]
    if not 找到:
        continue
    for 类 in 找到:
        英 = str(getattr(类, "英文名", "") or "")
        断言(f"{文件} · {getattr(类, '名称', 类.__name__)}",
             bool(英) and 界面文字.可用(英), f"英文名 = {英!r}")

# ---------------------------------------------------------------------------
# ③ 已知动态文本
# ---------------------------------------------------------------------------
print("\n③ 已知动态文本（面板会画到它们）")
样例 = [
    "空闲", "录制中", "采样中", "辨识中", "就绪", "不支持",
    "等待仿真侧…", "正在加载",
    "空场景（无机械臂）", "Franka Emika Panda", "Universal Robots UR5e",
    "最大误差(deg)", "力矩峰值(Nm)", "已采样步数", "已录行数",
    "正在激励采样（2.0 秒）…", "辨识中（后台线程）…",
    "✓ 已切换到 Franka Emika Panda（7 轴、耗时 12 ms）",
    "✗ 加载失败（已保留原模型）：ValueError: bad xml",
    "正在加载 UR5e（7 轴、耗时 12 ms）",
    "✓ 已切换到 空场景（无机械臂）",
]
for 文本 in 样例:
    英 = 界面文字.英文(文本)
    好 = bool(英) and 界面文字.可用(英)
    断言(f"{文本[:34]}", 好, f"→ {英!r}")

# 回归检查：单字替换踩过的坑 —— "进行"里的"行"绝不能被当成单位
断言("单字替换回归（'仿真进行中' 不能翻成 'rows'）",
     "rows" not in 界面文字.英文("仿真进行中，请稍候"),
     f"→ {界面文字.英文('仿真进行中，请稍候')!r}")
断言("'7 轴' 仍要正确翻成 '7 axes'",
     "7 axes" in 界面文字.英文("当前 7 轴"),
     f"→ {界面文字.英文('当前 7 轴')!r}")

# ---------------------------------------------------------------------------
# ④ 曲线名唯一化（曲线基类）
# ---------------------------------------------------------------------------
print("\n④ 曲线名（来自插件 指标()）")
try:
    监控 = __import__("监控面板").监控面板()
    for 名 in ("最大误差(deg)", "力矩峰值(Nm)", "未知的中文指标", "未知的中文指标"):
        监控.记一点(名, 0.1, 0.0)
    标签 = [str(线.get("界面名", "")) for 线 in 监控.曲线.values()]
    断言("曲线标签全是 ASCII", all(界面文字.可用(t) for t in 标签), f"→ {标签}")
    断言("曲线标签互不重名", len(set(标签)) == len(标签), f"→ {标签}")
    断言("未知中文名有兜底标签（chN 或英文）",
         all(t for t in 标签), f"→ {标签}")
except Exception as 异常:                                                # noqa: BLE001
    断言("曲线基类检查", False, f"{type(异常).__name__}: {异常}")

# ---------------------------------------------------------------------------
# ⑤ 静态扫描（复用 字体覆盖.py）
# ---------------------------------------------------------------------------
print("\n⑤ 静态扫描面板代码字面量（转调 字体覆盖.py）")
结果 = subprocess.run([sys.executable, os.path.join(本目录, "字体覆盖.py")],
                      capture_output=True, text=True)
断言("软件/面板/*.py 里没有画不出来的字面量", 结果.returncode == 0,
     "（详表见 优化/验证/字体覆盖_实测.txt）")

print("\n" + "=" * 70)
print(f"  面板文字验收：通过 {通过} 项 / 失败 {失败} 项")
print("=" * 70)
raise SystemExit(0 if 失败 == 0 else 1)
