"""面板窗几何自检（不需要开窗口）：验证"假页签紧挨官方 Inspector、内容窗在右栏页签栏下方"。

用法：./.venv/bin/python "优化（软件优化的报告都放这里面来）/验证/面板窗自检.py"

★ 为什么这些必须是**纯函数**：位置每帧都要算，写死在窗口绘制里就只能靠肉眼验证；
  抽出来之后"官方改版面 / 窗口被拉极小 / 首帧没几何"这些边界能在终端里逐条钉住。
"""
from __future__ import annotations

import os
import sys

包根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
面板目录 = os.path.join(包根, "软件", "面板")
for p in (os.path.join(包根, "软件"), 面板目录):
    if p not in sys.path:
        sys.path.insert(0, p)

import 面板窗                                                          # noqa: E402

通过 = 0
失败 = 0
三D = (296.0, 22.0, 678.0, 746.0)      # 实测的官方 3D 视口
窗宽 = 1200.0


def 用例(名, 条件, 说明=""):
    global 通过, 失败
    if 条件:
        通过 += 1
        print(f"  ✓ {名}")
    else:
        失败 += 1
        print(f"  ✗ {名}" + (f"   —— {说明}" if 说明 else ""))


def 约等(甲, 乙, 容差=1e-6):
    return len(甲) == len(乙) and all(abs(float(a) - float(b)) <= 容差 for a, b in zip(甲, 乙))


def 主() -> int:
    print("面板窗几何自检")
    右 = 面板窗.右栏矩形(三D, 窗宽)
    用例("右栏矩形 = (974,22,226,746)", 约等(右, (974.0, 22.0, 226.0, 746.0)), str(右))
    条 = 面板窗.算页签条矩形(三D, 窗宽)
    用例("整条页签栏由我们接管 = (974,22,226,24)", 约等(条, (974.0, 22.0, 226.0, 24.0)), str(条))
    格0 = 面板窗.算页签格矩形(三D, 窗宽, 0, 46.0)
    用例("格 0 = 官方 Inspector（只在那一行里，不动它的内容）",
        约等(格0, (974.0, 22.0, 124.0, 24.0)), str(格0))
    用例("旧名 官方页签矩形 仍指向格 0", 约等(面板窗.官方页签矩形(三D, 窗宽), 格0))
    格1 = 面板窗.算页签格矩形(三D, 窗宽, 1, 46.0)
    用例("格 1 = 我们的 Panels，紧挨格 0 右边（x = 974+124+2 = 1100）",
        约等(格1, (1100.0, 22.0, 70.0, 24.0)), str(格1))
    用例("两格不重叠、都不越出右栏",
        格0[0] + 格0[2] <= 格1[0] and 格1[0] + 格1[2] <= 1200.0,
        f"{格0} / {格1}")
    用例("点击一定落在我们手上（整条 = 两格 + 缝，且从右栏左边界起算）",
        abs((格1[0] + 格1[2]) - 1170.0) <= 1e-6 and 格0[0] == 条[0]
        and 格0[2] + 2.0 + 格1[2] <= 条[2])
    内容 = 面板窗.算面板窗矩形(三D, 窗宽)
    用例("内容窗在页签栏正下方 = (974,46,226,722)", 约等(内容, (974.0, 46.0, 226.0, 722.0)), str(内容))
    用例("内容窗盖住官方 Inspector 内容区（同一列、同一左边界）",
        约等(内容[:1], 右[:1]) and 约等(内容[2:3], 右[2:3]))
    用例("内容窗不压官方页签那一行（y ≥ 46）", 内容[1] >= 格0[1] + 格0[3])
    用例("正常几何 → 画", 面板窗.能画吗(三D, 窗宽) is True)
    用例("零几何（首帧）→ 不画", 面板窗.能画吗((0.0, 0.0, 0.0, 0.0), 窗宽) is False)
    用例("窗口被拉到极窄（右栏只剩 60）→ 不画",
        面板窗.能画吗((296.0, 22.0, 844.0, 746.0), 1200.0) is False)
    用例("窗口很矮 → 不画", 面板窗.能画吗((296.0, 22.0, 678.0, 120.0), 窗宽) is False)
    用例("NaN 几何 → 不画", 面板窗.能画吗((float("nan"), 22.0, 678.0, 746.0), 窗宽) is False)
    用例("右侧没有空间（3D 占满窗口）→ 不画",
        面板窗.能画吗((0.0, 22.0, 1200.0, 746.0), 窗宽) is False)
    名册 = __import__("面板注册表").名册
    用例("名册 7 个面板（模型库 → 关于）", len(名册) == 7, str(名册))
    print(f"\n结果：{通过} 通过 / {失败} 失败")
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
