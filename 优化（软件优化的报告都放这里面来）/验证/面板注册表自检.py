"""面板注册表语义自检（不需要开窗口）：验证"窗口开关 / 老状态迁移 / 段展开 / F9 / 重置版面"。

用法：./.venv/bin/python "优化（软件优化的报告都放这里面来）/验证/面板注册表自检.py"

★ 面板窗版（v3 契约）与旧版的关键差别，都在用例里钉住：
  ①「容器可见」→「标签条可见」→「面板窗可见」是同一个开关的三代名字，都要认
  ②「弹出」（v1 的独立浮动窗口）**不迁移** —— 否则用户一开软件就有面板压着 3D
  ③「钉住」（v2）语义等于 v3 的「展开的段」，照收
  ④ `独立窗口 = True` 的面板（展示=物理总闸 / 外观）不受窗口开关连坐
"""
from __future__ import annotations

import importlib
import json
import os
import sys
import tempfile

包根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
面板目录 = os.path.join(包根, "软件", "面板")
for p in (os.path.join(包根, "软件"), 面板目录):
    if p not in sys.path:
        sys.path.insert(0, p)

状态文件 = os.path.join(包根, "输出", "面板.json")
老状态文件 = os.path.join(包根, "输出", "面板状态.json")
备份 = {}


def 读路径(路径):
    try:
        with open(路径, encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return None


def 写路径(路径, 文本):
    os.makedirs(os.path.dirname(路径), exist_ok=True)
    with open(路径, "w", encoding="utf-8") as f:
        f.write(文本)


def 还原():
    for 路径, 内容 in 备份.items():
        if 内容 is None:
            if os.path.exists(路径):
                os.remove(路径)
        else:
            写路径(路径, 内容)


class 假面板:
    def __init__(self, 名, 独立窗口=False):
        self.面板显示名 = 名
        self.独立窗口 = 独立窗口
        self.可见 = False


class 面板窗:                     # 假的面板窗：只为让 注册.有容器() 认出来（按类名判断）
    def __init__(self):
        self.面板显示名 = "面板窗"
        self.可见 = True


def 重载():
    import 面板注册表
    模块 = importlib.reload(面板注册表)
    模块.重置缓存()          # 自检要反复换状态文件验证，所以每次重载都清一遍内存状态
    return 模块


def 用例(说明, 条件, 细节=""):
    print(f"  {'✓' if 条件 else '✗'} {说明}" + (f"   [{细节}]" if 细节 and not 条件 else ""))
    return bool(条件)


def main() -> int:
    print("=" * 74)
    print("  面板注册表 语义自检（面板窗版：窗口开关 / 迁移 / 段展开 / F9 / 重置版面）")
    print("=" * 74)
    备份[状态文件] = 读路径(状态文件)
    备份[老状态文件] = 读路径(老状态文件)
    通过 = 0
    总数 = 0
    try:
        # ---- ① 窗口开关 → 面板可见性；独立窗口不被连坐 ----
        print("\n① 面板窗开关 → 面板可见性；★窗口开关不落盘（坑②的教训）")
        写路径(状态文件, json.dumps({"版本": 3, "面板窗可见": False, "展开的段": {}},
                                    ensure_ascii=False))
        注册 = 重载()
        甲, 乙 = 假面板("模型库"), 假面板("实时监控")
        展示 = 假面板("展示", 独立窗口=True)
        注册.每帧(甲); 注册.每帧(乙); 注册.每帧(展示)
        总数 += 3
        通过 += 用例('★ 存档里写着"关"也不听：启动一律显示面板窗',
                    注册.面板窗可见() is True)
        通过 += 用例("所以名册里的面板启动就是可见的", 甲.可见 is True and 乙.可见 is True)
        通过 += 用例("独立窗口的面板不受影响（物理总闸不能被藏）", 展示.可见 is True)
        注册.设面板窗可见(False)
        注册.每帧(甲); 注册.每帧(乙); 注册.每帧(展示)
        总数 += 2
        通过 += 用例("运行中关掉面板窗 → 名册面板不可见", 甲.可见 is False and 乙.可见 is False)
        通过 += 用例("关窗口不影响独立窗口的面板", 展示.可见 is True)
        注册.全部显示()
        总数 += 2
        通过 += 用例("F9（全部显示）→ 面板窗显示", 注册.面板窗可见() is True)
        通过 += 用例("F9 之后面板都可见，且至少展开一段（不会开了窗却空着）",
                    甲.可见 is True and 乙.可见 is True and len(注册.展开的段()) >= 1)

        # ---- ② 老状态文件迁移：老版把所有面板都关了 → 面板窗默认收起 ----
        print("\n② 老版状态迁移（老文件里面板全关 = 用户想清屏 → 面板窗默认收起）")
        if os.path.exists(状态文件):
            os.remove(状态文件)
        写路径(老状态文件, json.dumps({"关于": False, "外观": False, "模型库": False},
                                    ensure_ascii=False))
        注册 = 重载(); 注册.每帧(假面板("外观"))
        总数 += 1
        通过 += 用例("老文件全关 → 面板窗收起", 注册.面板窗可见() is False)
        if os.path.exists(状态文件):
            os.remove(状态文件)
        写路径(老状态文件, json.dumps({"关于": False, "外观": True}, ensure_ascii=False))
        注册 = 重载(); 注册.每帧(假面板("外观"))
        总数 += 1
        通过 += 用例("老文件里有开着的 → 面板窗显示", 注册.面板窗可见() is True)

        # ---- ③ 三代存档容错 ----
        print("\n③ 旧存档（容器可见 / 标签条可见 / 弹出 / 钉住）读进来不炸、且按语义迁移")
        写路径(状态文件, json.dumps({"容器可见": False, "当前页签": "外观",
                                    "弹出": {"模型库": True}}, ensure_ascii=False))
        注册 = 重载(); 注册.每帧(假面板("模型库"))
        总数 += 3
        通过 += 用例("v1「容器可见=False」不再影响启动（窗口开关不落盘）",
                    注册.面板窗可见() is True)
        通过 += 用例("v1「弹出」不迁移成展开（否则一开软件就压着 3D）", 注册.展开的段() == [])
        通过 += 用例("v1「当前页签」不迁移", 注册.上次展开() == "")
        写路径(状态文件, json.dumps({"版本": 2, "标签条可见": False, "钉住": {"模型库": True}},
                                    ensure_ascii=False))
        注册 = 重载(); 注册.每帧(假面板("模型库"))
        总数 += 2
        通过 += 用例("v2「标签条可见=False」同样不再影响启动", 注册.面板窗可见() is True)
        通过 += 用例("v2「钉住」→ 展开的段（语义相同，照收）", 注册.段展开("模型库") is True)

        # ---- ④ 段展开语义 ----
        print("\n④ 段展开：可同时展开多个；全部段；跳到段")
        注册 = 重载()
        注册.设面板窗可见(True)
        注册.每帧(面板窗())
        for 名 in ("模型库", "算法", "控制器参数", "参数辨识", "实时监控", "数据录制", "关于", "野面板"):
            注册.每帧(假面板(名))
        总数 += 1
        通过 += 用例("面板窗已登记（有容器() 为真）", 注册.有容器() is True)
        注册.设段展开("模型库", True)
        注册.设段展开("实时监控", True)
        总数 += 2
        通过 += 用例("可以同时展开多个段", sorted(注册.展开的段()) == ["实时监控", "模型库"],
                    str(注册.展开的段()))
        通过 += 用例("展开中的面板由面板窗画（自己不开窗口）", 注册.画在容器里(假面板("模型库")) is True)
        注册.设段展开("模型库", False)
        总数 += 1
        通过 += 用例("收起某一段只影响它自己", 注册.展开的段() == ["实时监控"], str(注册.展开的段()))
        注册.全部段(True)
        总数 += 1
        通过 += 用例("全部段(True)：名册 7 段全开", len([n for n in 注册.展开的段() if n in 注册.名册]) == 7)
        注册.全部段(False)
        总数 += 1
        通过 += 用例("全部段(False)：全收", 注册.展开的段() == [])
        注册.设面板窗可见(False)
        注册.跳到段("算法")
        总数 += 2
        通过 += 用例("跳到段：会把面板窗打开", 注册.面板窗可见() is True)
        通过 += 用例("跳到段：那一段被展开", 注册.段展开("算法") is True)

        # ---- ⑤ 名册与"不在名册里的面板" ----
        print("\n⑤ 名册：段顺序、不在名册里的面板必须自己开窗口（不许两头都不画）")
        注册 = 重载()
        注册.设面板窗可见(True)
        注册.每帧(面板窗())
        for 名 in ("模型库", "算法", "控制器参数", "参数辨识", "实时监控", "数据录制", "关于", "野面板"):
            注册.每帧(假面板(名))
        顺序 = 注册.面板顺序()
        总数 += 2
        通过 += 用例("段顺序 = 名册 7 段 + 野面板排最后",
                    顺序[:7] == list(注册.名册) and 顺序[-1] == "野面板", str(顺序))
        通过 += 用例("不在名册里的面板：不归面板窗画（让它自己开窗口）",
                    注册.画在容器里(假面板("野面板")) is False)

        # ---- ⑥ 存档 v3 结构 ----
        print("\n⑥ 状态文件升到 v3（不再记「面板被关掉」）")
        注册.设段展开("模型库", True)
        文本 = 读路径(状态文件) or ""
        数据 = json.loads(文本) if 文本.strip().startswith("{") else {}
        总数 += 4
        通过 += 用例("存档里有 版本=3", 数据.get("版本") == 3, 文本[:80])
        通过 += 用例("存档里**不**记窗口开关（窗口开关不落盘 = 坑②的教训）",
                    "面板窗可见" not in 数据 and "标签条可见" not in 数据 and "容器可见" not in 数据)
        通过 += 用例("存档里**不**记「面板被关掉」这类状态",
                    not any(k in 数据 for k in ("关闭", "隐藏", "可见的面板")))
        通过 += 用例("展开的段里只有 true（没有「被关掉」这种记录）",
                    all(bool(v) for v in (数据.get("展开的段") or {}).values()))

        # ---- ⑦ 存档里的陌生名字必须容错 ----
        print("\n⑦ 存档里出现已经不存在面板名 → 不崩、不生效")
        写路径(状态文件, json.dumps({"版本": 3, "面板窗可见": True,
                                    "展开的段": {"早就没有的面板": True}, "上次展开": "也不存在"},
                                   ensure_ascii=False))
        注册 = 重载()
        炸了 = ""
        try:
            注册.每帧(假面板("模型库"))
        except Exception as 异常:                                            # noqa: BLE001
            炸了 = f"{type(异常).__name__}: {异常}"
        总数 += 2
        通过 += 用例("带陌生名字的存档不会让它崩", 炸了 == "", 炸了)
        通过 += 用例("陌生展开名不进展开的段", 注册.展开的段() == [], str(注册.展开的段()))

        # ---- ⑧ 重置版面：只清我们自己的窗口记录，不动官方布局 ----
        print("\n⑧ 重置版面（清理 ~/.mujoco.ini 里我们这些窗口的记录）")
        ini = os.path.join(tempfile.mkdtemp(), "fake.ini")
        写路径(ini, "\n".join([
            "[Window][Dockspace]", "Pos=0,22", "Size=1200,746", "",
            "[Window][Options]", "Pos=0,22", "DockId=0x00000001,0", "",
            "[Window][Model library]", "Pos=12,56", "Size=360,460", "DockId=0x00000009,0", "",
            "[Window][Appearance]", "Pos=341,189", "DockId=0x00000009,1", "",
            "[Window][Workbench]", "Pos=323,233", "Size=765,448", "DockId=0x0000000A,0", "",
            "[Docking][Data]", "DockNode ID=0x00000009 Pos=341,189 Size=486,387", "",
            "[Studio][UX]", "theme=1", ""]))
        注册._IMGUI配置 = ini
        注册._清理ini()
        剩下 = 读路径(ini) or ""
        总数 += 6
        通过 += 用例("我们自己的窗口段被删掉（Model library）", "[Window][Model library]" not in 剩下)
        通过 += 用例("我们自己的窗口段被删掉（Appearance）", "[Window][Appearance]" not in 剩下)
        通过 += 用例("旧版页签容器的段也清掉（Workbench）", "[Window][Workbench]" not in 剩下)
        通过 += 用例("官方窗口段保留（Options）", "[Window][Options]" in 剩下)
        通过 += 用例("残留的 DockId 行被清掉", "DockId" not in 剩下)
        # ★ 回归防线：第一版清理把"跳过"标志一直带下去，把删掉的窗口**之后**的段落全吞了。
        通过 += 用例("官方停靠数据与主题都保留",
                    "[Docking][Data]" in 剩下 and "[Studio][UX]" in 剩下 and "theme=1" in 剩下)
    finally:
        还原()

    print("\n" + "=" * 74)
    print(f"  结果：{通过}/{总数} 项通过")
    print("=" * 74)
    return 0 if 通过 == 总数 else 1


if __name__ == "__main__":
    raise SystemExit(main())
